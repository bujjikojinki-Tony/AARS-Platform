def field_label(field_name: str) -> str:
    return FIELD_DICTIONARY.get(field_name, {}).get("label", field_name)


def field_definition(field_name: str) -> str:
    return FIELD_DICTIONARY.get(field_name, {}).get("definition", "")


def build_field_dictionary_rows(group: str | None = None) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for field_name, payload in FIELD_DICTIONARY.items():
        if group is not None and payload.get("group") != group:
            continue
        rows.append(
            {
                "field_name": field_name,
                "label": payload.get("label", field_name),
                "group": payload.get("group", "-"),
                "definition": payload.get("definition", ""),
                "values": payload.get("values", ""),
                "source": payload.get("source", ""),
            }
        )
    return rows
